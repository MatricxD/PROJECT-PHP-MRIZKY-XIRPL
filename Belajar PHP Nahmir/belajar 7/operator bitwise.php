<?php

$a = 60;
$b = 13;

// bitwise AND
$c = $a & $b;
print "$a & $b = $c";
print "<br>";

// bitwise OR
$c = $a | $b;
print "$a | $b = $c";
print "<br>";

// bitwise XOR
$c = $a ^ $b;
print "$a ^ $b = $c";
print "<br>";

// Shift Left
$c = $a << $b;
print "$a << $b = $c";
print "<br>";

// Shift Right
$c = $a >> $b;
print "$a >> $b = $c";
print "<br>";